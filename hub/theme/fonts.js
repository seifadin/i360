// i360 theme fonts: Amiri and Amiri Quran, taken from the @fontsource npm
// packages (Google Fonts' own files, split by script).
//
//   node theme/fonts.js            is there a newer version? (never fails)
//   node theme/fonts.js --strict   same, but exits 1 when there is one or the
//                                  check itself failed (the monthly reminder)
//   node theme/fonts.js --apply    update: new files in fonts/<font>/<version>/,
//                                  the Fonts section of theme.css rewritten,
//                                  the folder before the current one removed
//
// npm run push runs the check and, when there's a newer version, the update,
// the tests and a separate commit before pushing (scripts/push.js).
//
// Safety check: a new file must have every character its current one has
// (for Amiri Quran: every Quranic mark), or the update stops.

import fs from 'fs';
import os from 'os';
import path from 'path';
import crypto from 'crypto';
import { execFileSync } from 'child_process';
import * as woff2 from './woff2.js';

const SITE = process.env.I360_THEME_SITE || path.join(import.meta.dirname, 'site');   // the variable: tests only
const FONTS = path.join(SITE, 'fonts');
const THEME_CSS = path.join(SITE, 'theme.css');
const REGISTRY = process.env.I360_NPM_REGISTRY || 'https://registry.npmjs.org';
const MARK = '/* ---------- Fonts ---------- */';

const PACKAGES = [
  { pkg: '@fontsource/amiri', dir: 'amiri', family: 'Amiri', prefix: 'amiri', weights: [400, 700], subsets: ['arabic', 'latin-ext', 'latin'] },
  { pkg: '@fontsource/amiri-quran', dir: 'amiri-quran', family: 'Amiri Quran', prefix: 'amiri-quran', weights: [400], subsets: ['arabic', 'latin'] }
];

const fileName = (p, subset, w) => `${p.prefix}-${subset}-${w}-normal.woff2`;
const files = (p) => p.weights.flatMap((w) => p.subsets.map((s) => ({ w, s, name: fileName(p, s, w) })));

// Version folder theme.css uses now, per package.
function currentVersions(css = fs.readFileSync(THEME_CSS, 'utf8')) {
  const out = {};
  for (const p of PACKAGES) {
    const m = new RegExp(`url\\(fonts/${p.dir}/([^/]+)/`).exec(css);
    out[p.dir] = m ? m[1] : null;
  }
  return out;
}

// a < b for x.y.z versions
function older(a, b) {
  const pa = String(a).split('.').map(Number), pb = String(b).split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) < (pb[i] || 0);
  }
  return false;
}

async function fetchOk(url, what) {
  let res;
  try { res = await fetch(url, { signal: AbortSignal.timeout(20000) }); } catch (e) {
    throw new Error(`${what}: no answer from ${new URL(url).host} (${(e.cause && e.cause.code) || e.name || e.message})`, { cause: e });
  }
  if (!res.ok) throw new Error(`${what}: HTTP ${res.status} from ${new URL(url).host}`);
  return res;
}

// What npm has now, per package: { dir, pkg, current, latest, tarball, integrity, newer }
async function check() {
  const cur = currentVersions();
  const out = [];
  for (const p of PACKAGES) {
    const meta = await (await fetchOk(`${REGISTRY}/${p.pkg}/latest`, `checking ${p.pkg}`)).json();
    if (!meta.version || !meta.dist || !meta.dist.tarball) throw new Error(`checking ${p.pkg}: unexpected answer from the npm registry`);
    out.push({ ...p, current: cur[p.dir], latest: meta.version, tarball: meta.dist.tarball, integrity: meta.dist.integrity, newer: !cur[p.dir] || older(cur[p.dir], meta.version) });
  }
  return out;
}

async function download(info, tmp) {
  const buf = Buffer.from(await (await fetchOk(info.tarball, `downloading ${info.pkg} ${info.latest}`)).arrayBuffer());
  const m = /^sha512-(.+)$/.exec(info.integrity || '');
  if (!m) throw new Error(`downloading ${info.pkg}: the registry gave no sha512 checksum`);
  if (crypto.createHash('sha512').update(buf).digest('base64') !== m[1]) throw new Error(`downloading ${info.pkg}: checksum mismatch`);
  const tgz = path.join(tmp, `${info.dir}.tgz`), out = path.join(tmp, info.dir);
  fs.writeFileSync(tgz, buf);
  fs.mkdirSync(out, { recursive: true });
  execFileSync('tar', ['-xzf', tgz, '-C', out]);
  return path.join(out, 'package');
}

// unicode-range of each subset/weight, from the package's own CSS
function ranges(pkgDir, p) {
  const out = {};
  for (const w of p.weights) {
    const css = fs.readFileSync(path.join(pkgDir, `${w}.css`), 'utf8');
    for (const s of p.subsets) {
      const m = new RegExp(`/\\* ${p.prefix}-${s}-${w}-normal \\*/[\\s\\S]*?unicode-range:\\s*([^;]+);`).exec(css);
      if (!m) throw new Error(`${p.pkg}: no unicode-range for ${s} ${w} in ${w}.css`);
      out[`${s}-${w}`] = m[1].trim();
    }
  }
  return out;
}

function fontsSection(entries) {
  const lines = [MARK,
    '/* Generated by theme/fonts.js — do not edit by hand. Each font is split by',
    '   script (unicode-range), so a page downloads only the parts it uses.',
    '   font-display: block — text waits for Amiri (about 3 s at most, first visit only)',
    '   instead of drawing a fallback font and then reflowing (i360-instructions.md §14g).',
    ...entries.map((e) => `   ${e.family}: ${e.pkg} ${e.version} (font ${e.fontVersion}), licence fonts/${e.dir}/${e.version}/OFL.txt`),
    '*/'];
  for (const e of entries) {
    for (const f of files(e)) {
      lines.push(`@font-face {
  font-family: '${e.family}';
  font-style: normal;
  font-weight: ${f.w};
  font-display: block;
  src: url(fonts/${e.dir}/${e.version}/${f.name}) format('woff2');
  unicode-range: ${e.ranges[`${f.s}-${f.w}`]};
}`);
    }
  }
  return lines.join('\n') + '\n';
}

// Ranges of the files in use now, read back from theme.css (to rewrite the section unchanged for a package that isn't updated).
function rangesFromCss(css, p, version) {
  const out = {};
  for (const f of files(p)) {
    const m = new RegExp(`url\\(fonts/${p.dir}/${version.replace(/\./g, '\\.')}/${f.name}\\)[^;]*;\\s*unicode-range:\\s*([^;]+);`).exec(css);
    if (!m) throw new Error(`theme.css: no @font-face for fonts/${p.dir}/${version}/${f.name}`);
    out[`${f.s}-${f.w}`] = m[1].trim();
  }
  return out;
}

function sectionEntryFromDisk(p, version, rangesMap) {
  const v = woff2.versionString(fs.readFileSync(path.join(FONTS, p.dir, version, files(p)[0].name))) || '?';
  return { ...p, version, ranges: rangesMap, fontVersion: v.replace(/^Version\s*/i, '') };
}

/**
 * Update every package that has a newer version. All or nothing: on any
 * error, what was written is removed and theme.css is put back.
 * Returns [{ family, from, to, fontFrom, fontTo, removed }].
 */
async function apply(infos) {
  infos = infos || await check();
  const todo = infos.filter((i) => i.newer);
  if (!todo.length) return [];
  const cssBefore = fs.readFileSync(THEME_CSS, 'utf8');
  if (!cssBefore.includes(MARK)) throw new Error(`theme.css has no "${MARK}" line`);
  const created = [];
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'i360-fonts-'));
  const report = [];
  try {
    const entries = [];
    for (const info of infos) {
      if (!info.newer) {
        entries.push(sectionEntryFromDisk(info, info.current, rangesFromCss(cssBefore, info, info.current)));
        continue;
      }
      const pkgDir = await download(info, tmp);
      const dest = path.join(FONTS, info.dir, info.latest);
      if (fs.existsSync(dest)) throw new Error(`${dest} already exists`);
      fs.mkdirSync(dest, { recursive: true });
      created.push(dest);
      let fontFrom = null, fontTo = null;
      for (const f of files(info)) {
        const src = path.join(pkgDir, 'files', f.name);
        if (!fs.existsSync(src)) throw new Error(`${info.pkg} ${info.latest} has no ${f.name}`);
        const fresh = fs.readFileSync(src);
        const now = woff2.codePoints(fresh);
        if (info.current) {
          const oldBuf = fs.readFileSync(path.join(FONTS, info.dir, info.current, f.name));
          const lost = [...woff2.codePoints(oldBuf)].filter((c) => !now.has(c));
          if (lost.length) {
            throw new Error(`safety check: ${info.family} ${info.latest} ${f.name} lacks ${lost.slice(0, 8).map((c) => 'U+' + c.toString(16).toUpperCase().padStart(4, '0')).join(', ')}${lost.length > 8 ? ` and ${lost.length - 8} more` : ''}`);
          }
          fontFrom = fontFrom || woff2.versionString(oldBuf);
        }
        fontTo = fontTo || woff2.versionString(fresh);
        fs.writeFileSync(path.join(dest, f.name), fresh);
      }
      fs.copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(dest, 'OFL.txt'));
      if (!/SIL Open Font License, Version 1\.1/.test(fs.readFileSync(path.join(dest, 'OFL.txt'), 'utf8'))) {
        throw new Error(`${info.pkg} ${info.latest}: the licence is no longer the SIL Open Font License 1.1 — check it by hand`);
      }
      entries.push({ ...info, version: info.latest, ranges: ranges(pkgDir, info), fontVersion: (fontTo || '?').replace(/^Version\s*/i, '') });
      report.push({ family: info.family, from: info.current, to: info.latest, fontFrom, fontTo, removed: [] });
    }
    const css = cssBefore.slice(0, cssBefore.indexOf(MARK)) + fontsSection(entries);
    fs.writeFileSync(THEME_CSS, css);
    // Keep the folder just replaced (saved copies of the old theme.css still
    // point at it); remove any older one.
    for (const r of report) {
      const p = PACKAGES.find((x) => x.family === r.family);
      for (const v of fs.readdirSync(path.join(FONTS, p.dir))) {
        if (v !== r.to && v !== r.from) { fs.rmSync(path.join(FONTS, p.dir, v), { recursive: true }); r.removed.push(v); }
      }
    }
    return report;
  } catch (e) {
    for (const d of created) fs.rmSync(d, { recursive: true, force: true });
    fs.writeFileSync(THEME_CSS, cssBefore);
    throw e;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

const describe = (i) => `${i.family}: ${i.current || 'none'}${i.newer ? ` → ${i.latest} available` : ' (newest)'}`;

export { PACKAGES, MARK, check, apply, currentVersions, older, fontsSection, rangesFromCss, sectionEntryFromDisk, describe, THEME_CSS, FONTS };

if (process.argv[1] === import.meta.filename) {
  const arg = process.argv[2] || '';
  (async () => {
    if (arg === '--apply') {
      const report = await apply();
      if (!report.length) { console.log('Fonts: already the newest.'); return; }
      for (const r of report) console.log(`Fonts: ${r.family} ${r.from} → ${r.to} (${r.fontFrom || '?'} → ${r.fontTo || '?'})${r.removed.length ? `; removed ${r.removed.join(', ')}` : ''}`);
      return;
    }
    let infos;
    try { infos = await check(); } catch (e) {
      console.log(`Fonts: could not check — ${e.message}`);
      if (arg === '--strict') process.exitCode = 1;
      return;
    }
    for (const i of infos) console.log(`Fonts: ${describe(i)}`);
    if (arg === '--strict' && infos.some((i) => i.newer)) {
      console.log('A newer font is available: run npm run push (or node theme/fonts.js --apply).');
      process.exitCode = 1;
    }
  })().catch((e) => { console.error(`Fonts: update failed — ${e.message}`); process.exitCode = 1; });
}
